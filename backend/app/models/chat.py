from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional, Literal

class ChatMessage(BaseModel):
    role: str = Field(..., description="Role of the message sender, e.g., 'user' or 'assistant'")
    content: str = Field(..., description="Content of the message")

class ChatRequest(BaseModel):
    messages: List[ChatMessage] = Field(..., description="List of previous conversation messages")
    query: str = Field(..., description="The latest user query to answer")
    mode: Literal["llm", "rag"] = Field("llm", description="Response mode: 'llm' for Ollama-synthesised answer, 'rag' for direct structured results")

class ChatResponse(BaseModel):
    answer: str = Field(..., description="The chatbot answer generated by the local LLM")
    sources: List[Dict[str, Any]] = Field(default=[], description="List of CSV records used as context sources")
    response_mode: Literal["llm", "rag"] = Field("llm", description="Which mode actually produced this response (may differ from requested mode on fallback)")
